import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
const executablePath=process.env.BROWSER_PATH||['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
if(!executablePath)throw new Error('Set BROWSER_PATH to an installed Chromium executable.');
const browser=await chromium.launch({executablePath,headless:true}),errors=[];let page;
try{
  page=await browser.newPage({viewport:{width:1440,height:1050}});page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:3000/#home');
  await page.locator('#recently-watched').waitFor();
  assert.equal(await page.locator('.recent-card').count(),0);
  assert.equal(await page.getByText('Test providers',{exact:true}).count(),0);
  await page.goto('http://127.0.0.1:3000/#anime/1642');
  await page.locator('.play-episode').waitFor({timeout:90000});
  assert.equal(await page.locator('#source-select').count(),0);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('anikoto-recently-watched')||'[]').length),0,'Opening a detail page must not count as watching.');
  await page.locator('.play-episode').click();
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>2,null,{timeout:35000});
  await page.locator('video').evaluate(v=>v.currentTime=15);
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>16,null,{timeout:25000});
  await page.locator('video').evaluate(v=>v.pause());
  await page.getByRole('link',{name:'Discover',exact:true}).click();
  await page.locator('.recent-card').waitFor();
  assert.equal(await page.locator('.recent-card').count(),1);
  assert.match(await page.locator('.recent-card h3').innerText(),/One Piece/);
  assert.match(await page.locator('.recent-card').getAttribute('href'),/episode\/1$/);
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('anikoto-recently-watched'))[0]);assert.ok(saved.position>=15);assert.ok(saved.duration>0);
  await mkdir(new URL('../.local-results/',import.meta.url),{recursive:true});
  await page.screenshot({path:'.local-results/recently-watched-desktop.png',fullPage:true});
  await page.reload();await page.locator('.recent-card').waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'.local-results/recently-watched-mobile.png',fullPage:true});
  await page.locator('.recent-card').click();
  await page.locator('.play-episode').waitFor({timeout:90000});
  await page.locator('.play-episode').click();
  await page.waitForFunction(position=>{const v=document.querySelector('video');return v&&!v.paused&&v.currentTime>=position;},saved.position,{timeout:35000});
  const resumed=await page.locator('video').evaluate(v=>({time:v.currentTime,width:v.videoWidth,height:v.videoHeight}));
  await page.getByRole('link',{name:'Discover',exact:true}).click();
  await page.locator('#clear-recent').click();assert.equal(await page.locator('.recent-card').count(),0);
  await page.reload();await page.locator('#recently-watched').waitFor();assert.equal(await page.locator('.recent-card').count(),0);
  assert.equal(await page.locator('video').count(),0);assert.deepEqual(errors,[]);
  await writeFile(new URL('../.local-results/browser-report.json',import.meta.url),JSON.stringify({testedAt:new Date().toISOString(),saved,resumed,errors},null,2));
  console.log('Passed: AnimeParadise playback, no source switch, actual-watch history, saved progress, persistence, resume, clearing history, mobile layout, and navigation cleanup.');
}catch(error){if(page){console.error(JSON.stringify(await page.evaluate(()=>{const v=document.querySelector('video');return {url:location.href,status:document.querySelector('#playback-status')?.textContent,video:v?{time:v.currentTime,paused:v.paused,seeking:v.seeking,ready:v.readyState,duration:v.duration,error:v.error?.message,buffered:Array.from({length:v.buffered.length},(_,i)=>[v.buffered.start(i),v.buffered.end(i)])}:null};})));await page.screenshot({path:'.local-results/recent-test-failure.png',fullPage:true});}throw error;}finally{await browser.close();}
